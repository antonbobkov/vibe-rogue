// Every item in the game (21-items-catalog.md), shaped per TEC-03 `Item` and ITM-01.
//
// Transcription notes (all logged in specs/DECISIONS.md):
//  - Dice are kept as strings and parsed at load by `parseDice` (PLN-06 M02 task 1, D-014).
//  - `floors` is ITM-01's "set of floors whose floor and cache tables may contain it". An item that
//    only ever arrives another way — the starting Wrench, the two boss drops — has `floors: []`
//    (D-015). Enemy drop tables are exempt from `floors` by ITM-01, so they are not affected.
//  - Journal pages are nine `record` items named `Journal page 1` … `Journal page 8` and
//    `Understudy Blueprint` (CAT-07, D-016); their `floors` names the floor they are found on.
//  - Effect and special ids are the closed sets of TEC-04.
//
// Counts (CAT-08): 7 melee + 2 ranged weapons, 5 platings, 5 attachments, 7 consumables,
// 9 records; two unique items (Conductor's Baton, Governor).

